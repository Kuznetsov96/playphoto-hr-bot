/**
 * Скільки змін показати на екрані вибору. Двадцять однорядкових кнопок
 * телефон гортає без зусиль, а клавіатура Telegram вміщає їх із запасом.
 *
 * Це не сторінка, а стеля: у проді найдовший графік попереду — 13 змін, тож
 * у звичайний день зріз не спрацьовує взагалі й людина бачить усе. Стеля існує
 * рівно для аномалії (графік на пів року вперед), щоб екран не перетворився на
 * полотно з сотні кнопок.
 */
export const SHIFT_PICKER_VISIBLE_LIMIT = 20;

export type ShiftPickerView<T> = {
    visible: T[];
    hiddenCount: number;
    text: string;
};

/**
 * Вирішує, що показати і що сказати.
 *
 * Головне тут — друге. Старий екран мовчки різав список до восьми, і зникнення
 * зміни виглядало для фотографині як «її просто немає»: ані рядка про те, що
 * список неповний. Тому, коли зріз усе ж спрацював, він мусить назвати себе —
 * рівно як це давно робить адмінська дошка замін.
 */
export function buildShiftPickerView<T>(shifts: T[]): ShiftPickerView<T> {
    const visible = shifts.slice(0, SHIFT_PICKER_VISIBLE_LIMIT);
    const hiddenCount = shifts.length - visible.length;

    if (hiddenCount === 0) {
        return { visible, hiddenCount, text: "Обери дату і локацію." };
    }

    return {
        visible,
        hiddenCount,
        text:
            `Обери дату і локацію.\n\n` +
            `Показані найближчі ${visible.length} змін з ${shifts.length}. ` +
            `Решта з'явиться тут, щойно ці пройдуть.`
    };
}

/** Стан заявки, через який по зміні не можна запустити новий пошук. */
export type ReplacementBlockingStatus = "ACTIVE" | "FOUND" | "FAILED";

/**
 * Помітка на кнопці зміни, по якій новий пошук не запуститься.
 *
 * Такі зміни раніше просто зникали з екрана. Коли зникали всі, фотографиня
 * читала «У тебе немає майбутніх змін», хоча зміни були (01.10.2026). Тепер
 * зміна лишається на місці, і стан видно ще до дотику.
 */
export function pickerBlockedMark(status: ReplacementBlockingStatus): string {
    switch (status) {
        case "ACTIVE":
            return "🔎 пошук триває";
        case "FOUND":
            return "✅ підміну знайдено";
        case "FAILED":
            return "✖️ не знайшли";
    }
}

/**
 * Конкретна причина, чому пошук по цій зміні не запускається. Одна для
 * дотику в пікері і для відмови на «Почати пошук»: людина читає те саме
 * пояснення, хоч би яким шляхом дійшла до цієї зміни. Спливне вікно
 * Telegram тримає до 200 знаків.
 */
export function replacementBlockedReason(status: ReplacementBlockingStatus): string {
    switch (status) {
        case "ACTIVE":
            return "Пошук для цієї зміни вже триває. Щойно хтось погодиться — напишемо.";
        case "FOUND":
            return "Підміну для цієї зміни вже знайдено. Якщо графік ще не оновили, напиши в підтримку.";
        case "FAILED":
            return "Ти вже запускала пошук для цієї зміни, але підміну не знайшли. Напиши в підтримку — команда допоможе вручну.";
    }
}
