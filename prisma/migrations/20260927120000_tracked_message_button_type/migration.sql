-- Какую кнопку несёт рассылка: 'default' (подтвердить) или 'preferences'.
--
-- Пингер узнавал сбор пожеланий по слову «Побажання» в тексте рассылки. С
-- 21.08.2026 приглашение начинается с «Графік на …», слово ушло в нижний
-- регистр, и напоминания о пожеланиях уходили как обычная рассылка — с
-- кнопкой «Ознайомлена», нажатие на которую глушило пинги без подачи.
ALTER TABLE "TrackedMessage" ADD COLUMN "buttonType" TEXT NOT NULL DEFAULT 'default';

-- Месяц сбора пожеланий (`YYYY-MM`) у рассылки пожеланий. Срок и признак
-- «сбор открыт» пингер спрашивает у вебаппа по этому месяцу перед каждым
-- напоминанием — вместо зашитого в строку `pingUntil`. NULL у всех прочих.
ALTER TABLE "TrackedMessage" ADD COLUMN "targetMonth" TEXT;

-- Живые строки старого бота — только те, чьё окно напоминаний ещё идёт.
-- `pingUntil` ставил только сбор пожеланий (26-е 23:59 по Киеву месяца ПЕРЕД
-- графиком). Без этого выкат с 23-го по 26-е превратил бы живые напоминания в
-- рассылку с «Ознайомлена» — ту самую поломку, ради которой колонка появилась.
--
-- Истёкшие строки не трогаются, и `pingUntil` не сдвигается: старый пингер не
-- гасит `nextPingAt` по истечении окна, строки просто перестают выбираться.
-- Сдвинь им предел — и откат образа после миграции (автоматический, если
-- health-check не прошёл) разбудил бы напоминания с «Ознайомлена» всем, кто не
-- подал за сентябрь и октябрь.
--
-- `pingUntil` хранится без зоны, в UTC; месяц дедлайна берётся по Киеву,
-- месяц графика — следующий за ним.
UPDATE "TrackedMessage"
SET
  "buttonType" = 'preferences',
  "targetMonth" = to_char(
    date_trunc('month', ("pingUntil" AT TIME ZONE 'UTC') AT TIME ZONE 'Europe/Kyiv') + interval '1 month',
    'YYYY-MM'
  )
WHERE "pingUntil" IS NOT NULL
  AND "pingUntil" > (now() AT TIME ZONE 'UTC');
